#!/usr/bin/env python3
# hot_order.py <build dir> [out]: rewrites hot_order.ld, the .text order of the 3DS link (port/docs/3ds.md, PGO),
# from a build's LTO object (lto.o, its call graph profile), link map (gta2.map) and gta2.elf.
import bisect, os, re, shutil, subprocess, sys

build = sys.argv[1]
out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(os.path.dirname(os.path.abspath(__file__)), 'hot_order.ld')
tool = lambda name: shutil.which(name + '-22') or name

# The input sections of .text in the map: name, address, size, file.
secs, pend, inside = [], None, False
for line in open(os.path.join(build, 'gta2.map')):
    line = line.rstrip('\n')
    if line.startswith('.text '):
        inside = True
    elif inside and line and not line.startswith(' '):
        break
    elif inside:
        m = re.match(r'^ (\.\S+)?\s+0x([0-9a-f]+)\s+0x([0-9a-f]+)\s+(\S.*)$', line)
        if m and (m.group(1) or pend):
            if int(m.group(3), 16):
                secs.append((m.group(1) or pend, int(m.group(2), 16), int(m.group(3), 16), m.group(4)))
            pend = None
        else:
            m = re.match(r'^ (\.\S+)$', line)
            pend = m.group(1) if m else None
secs.sort(key=lambda s: s[1])
starts = [s[1] for s in secs]

def section_of(addr):
    i = bisect.bisect_right(starts, addr) - 1
    return i if i >= 0 and addr < secs[i][1] + secs[i][2] else None

syms = {}
for line in subprocess.run([tool('llvm-nm'), os.path.join(build, 'gta2.elf')], capture_output=True, text=True).stdout.splitlines():
    p = line.split()
    if len(p) == 3 and p[1] in 'tTwW':
        syms.setdefault(p[2], section_of(int(p[0], 16)))

# Call graph edges between sections, as LLVM's CGProfile pass weighed them from the PGO counts.
edges = {}
text = subprocess.run([tool('llvm-readobj'), '--cg-profile', os.path.join(build, 'lto.o')], capture_output=True, text=True).stdout
found = [(syms.get(f), syms.get(t), int(w)) for f, t, w in re.findall(r'From: (\S+) .*?\n\s*To: (\S+) .*?\n\s*Weight: (\d+)', text)]
# Calls under 1e-5 of the profile's (about one per ten logic steps), and never run code, stay out of the hot part.
least = sum(w for a, b, w in found) / 100000
for a, b, w in found:
    if a is not None and b is not None and a != b and w >= least and not any('.unlikely' in secs[n][0] for n in (a, b)):
        edges[a, b] = edges.get((a, b), 0) + w

# C3 (Ottoni and Maher, as lld's --call-graph-profile-sort): each section joins its heaviest caller's cluster.
weight, pred = {}, {}
for (a, b), w in edges.items():
    weight[b] = weight.get(b, 0) + w
    weight.setdefault(a, 0)
    if b not in pred or pred[b][1] < w:
        pred[b] = (a, w)
size = {n: secs[n][2] for n in weight}
members = {n: [n] for n in weight}
leader = {n: n for n in weight}
cw = dict(weight)
density = lambda n: cw[n] / size[n]

def find(n):
    while leader[n] != n:
        n = leader[n]
    return n

for n in sorted(weight, key=density, reverse=True):
    if n not in pred or pred[n][1] * 10 <= weight[n]:
        continue
    p = find(pred[n][0])
    if p == n or size[n] + size[p] > 1 << 20:
        continue
    if (cw[p] + cw[n]) / (size[p] + size[n]) < density(p) / 8:
        continue
    leader[n] = p
    members[p] += members.pop(n)
    size[p] += size[n]
    cw[p] += cw[n]

def pattern(n):
    name, _, _, path = secs[n]
    if 'lto-llvm' in path or os.path.basename(path) == 'lto.o':
        return '*(%s)' % name
    m = re.match(r'.*/([^/]+\.a)\(([^)]+)\)$', path)
    return '*%s:%s(%s)' % (m.group(1), m.group(2), name) if m else '*%s(%s)' % (os.path.basename(path), name)

order = [pattern(m) for c in sorted(members, key=density, reverse=True) if cw[c] for m in members[c]]
with open(out, 'w') as f:
    f.write('/* Generated by hot_order.py, for ld --section-ordering-file: the start of .text, crt0 first (3dsxtool),\n'
            '   the profiled calls in C3 order, the rest of the hot code, then all but .text.unlikely. */\n')
    f.write('.text : {\n\tKEEP( *(.crt0) )\n\tKEEP( *(.init) )\n\t. = ALIGN(4);\n')
    f.writelines('\t%s\n' % p for p in order)
    f.write('\t*(.text.hot .text.hot.*)\n\t*(.text .text.[!u]* .text.u[!n]* .text.un[!l]*)\n}\n')
print('%d sections in %d clusters, %d edges, %d KB' % (len(order), sum(1 for c in members if cw[c]), len(edges),
      sum(secs[m][2] for c in members if cw[c] for m in members[c]) // 1024))
